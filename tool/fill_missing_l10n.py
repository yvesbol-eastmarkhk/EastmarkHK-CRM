def main():
    langs = sorted(T.keys())
    print(f"Langues à traiter : {len(langs)}")
    for lang in langs:
        path = os.path.join(ARB_DIR, f"app_{lang}.arb")
        if not os.path.exists(path):
            print(f"  ! fichier introuvable : {path}")
            continue
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
        translations = T[lang]
        added = 0
        missing_in_dict = []
        for key in KEYS:
            if key in data:
                continue
            if key not in translations:
                missing_in_dict.append(key)
                continue
            data[key] = translations[key]
            meta = PLACEHOLDER_META.get(key)
            if meta:
                data["@" + key] = {"placeholders": meta}
            added += 1
        with open(path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            f.write("\n")
        status = f"app_{lang}.arb: +{added}"
        if missing_in_dict:
            status += f" (MANQUANT dans le dict: {missing_in_dict})"
        print(status)


if __name__ == "__main__":
    main()
