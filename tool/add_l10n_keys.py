def metadata_for(key, value):
    ph = PLACEHOLDER_KEYS.get(key)
    if not ph:
        return None
    # Détecte les placeholders présents dans le message.
    found = set(re.findall(r"\{(\w+)[,}]", value))
    md = {}
    for name, typ in ph.items():
        if name in found:
            md[name] = {"type": typ}
    if not md:
        return None
    return md


def insert_after(data, key, value, meta):
    # Insère la clé (et son @métadonnée) juste après la dernière clé,
    # en préservant l'ordre d'insertion (dict Python 3.7+).
    data[key] = value
    if meta:
        data["@" + key] = {"placeholders": meta}


